/// The file tools the hook checks.
pub const EDIT_TOOLS: [&str; 4] = ["Edit", "Write", "MultiEdit", "NotebookEdit"];

/// The settings matcher: the file tools and Bash.
pub const CHECK_MATCHER: &str = "Edit|Write|MultiEdit|NotebookEdit|Bash";

/// What the hook is asked about.
#[derive(Debug, Clone, PartialEq)]
pub struct CheckInput {
    pub tool_name: String,
    pub tool_input: serde_json::Value,
    pub cwd: PathBuf,
}

// one value per hook run, never stored: the Deny payload's size does not matter
#[allow(clippy::large_enum_variant)]
#[derive(Debug, Clone, PartialEq)]
pub enum CheckDecision {
    Allow,
    /// `path` for a denied write, `command` for a denied shell command; `other` the claim (the first named, for a
    /// command) that stopped it.
    Deny {
        repo: PathBuf,
        path: Option<String>,
        command: Option<String>,
        other: Option<Claim>,
        reason: String,
    },
}

/// The §5.3 reason, verbatim.
pub fn deny_reason(path: &str, other_title: &str) -> String {
    format!(
        "Fanout Code: another task, {other_title}, has uncommitted changes in {path}. The developer is being asked how \
         to proceed. Do not edit this file or work around the block; finish anything unrelated you were doing, then \
         stop and wait for the developer's instruction."
    )
}

/// The §5.6 reason: what the command would do to the other tasks' work, and each task with its files (`named`, in
/// order; a task named once however many of its files are listed).
pub fn git_deny_reason(kind: CommandKind, named: &[&Claim]) -> String {
    let mut tasks: Vec<(Option<&TaskId>, &str, Vec<&str>)> = Vec::new();
    for c in named {
        match tasks
            .iter_mut()
            .find(|(t, title, _)| *t == c.task_id.as_ref() && *title == c.title)
        {
            Some((_, _, paths)) => paths.push(&c.path),
            None => tasks.push((c.task_id.as_ref(), &c.title, vec![&c.path])),
        }
    }
    let holders: Vec<String> = tasks
        .iter()
        .map(|(_, title, paths)| format!("{title} has {}", paths.join(", ")))
        .collect();
    let would = match kind {
        CommandKind::Commits => "commit other tasks' uncommitted changes into this task's commit",
        CommandKind::Discards => "discard other tasks' uncommitted changes from the working tree",
    };
    format!(
        "Fanout Code: this git command would {would}: {}. The developer is being asked how to proceed. Do not run it \
         or work around the block; finish anything unrelated you were doing, then stop and wait for the developer's \
         instruction.",
        holders.join("; ")
    )
}

/// The tool input's target, resolved against `cwd` when relative.
fn target_path(input: &CheckInput) -> Option<PathBuf> {
    let raw = ["file_path", "notebook_path"]
        .iter()
        .find_map(|k| input.tool_input.get(*k).and_then(|v| v.as_str()))
        .filter(|s| !s.is_empty())?;
    let p = Path::new(raw);
    Some(clean(&if p.is_absolute() {
        p.to_owned()
    } else {
        input.cwd.join(p)
    }))
}

/// The other tasks' claims on `path` in `file`, minus those `grants` cover. This task's own claim on the path is
/// skipped, never a reason to allow: after it edited on top of another task's claim, that task's uncommitted
/// changes are still there, and only a grant (which it then holds) lets it go on.
fn uncovered<'a>(file: &'a ClaimsFile, path: &str, own: &TaskId, grants: &GrantsFile) -> Vec<&'a Claim> {
    file.claims
        .iter()
        .filter(|c| c.path == path && c.task_id.as_ref() != Some(own))
        .filter(|c| !grants.covers(&file.repo_root, path, c.task_id.as_ref()))
        .collect()
}

fn check_edit(input: &CheckInput, own: &TaskId, claims: &[ClaimsFile], grants: &GrantsFile) -> CheckDecision {
    let Some(target) = target_path(input) else {
        return CheckDecision::Allow;
    };
    // the deepest repo holding the path (a linked root may sit inside the home root)
    let found = claims
        .iter()
        .filter_map(|f| rel_in(&f.repo_root, &target).map(|rel| (f, rel)))
        .filter(|(_, rel)| !rel.is_empty())
        .min_by_key(|(_, rel)| rel.len());
    let Some((file, rel)) = found else {
        return CheckDecision::Allow;
    };
    match uncovered(file, &rel, own, grants).first() {
        None => CheckDecision::Allow,
        Some(claim) => CheckDecision::Deny {
            repo: file.repo_root.clone(),
            reason: deny_reason(&rel, &claim.title),
            path: Some(rel),
            command: None,
            other: Some((*claim).clone()),
        },
    }
}

fn check_bash(input: &CheckInput, own: &TaskId, claims: &[ClaimsFile], grants: &GrantsFile) -> CheckDecision {
    let Some(command) = input.tool_input.get("command").and_then(|c| c.as_str()) else {
        return CheckDecision::Allow;
    };
    for file in claims {
        // edit grants never let a command through (§5.6); only an exact, single-use `Command` grant does
        let others: Vec<&Claim> = file
            .claims
            .iter()
            .filter(|c| c.task_id.as_ref() != Some(own))
            .filter(|c| !grants.allows_command(command, &file.repo_root, c.task_id.as_ref()))
            .collect();
        let Some((rule, paths)) = evaluate_git(command, &input.cwd, &file.repo_root, &others) else {
            continue;
        };
        let named: Vec<&Claim> = others.iter().copied().filter(|c| paths.contains(&c.path)).collect();
        return CheckDecision::Deny {
            repo: file.repo_root.clone(),
            path: None,
            command: Some(command.to_owned()),
            other: named.first().map(|c| (*c).clone()),
            reason: git_deny_reason(rule_kind(rule), &named),
        };
    }
    CheckDecision::Allow
}

/// The `Command` grants a Bash call needs to pass the git guard: each repo and other task whose claims the command
/// touches there, with those paths and what it does to them, found segment hit by segment hit as `check_bash` would
/// once every earlier hit was granted.
fn command_grants_needed(input: &CheckInput, own: &TaskId, claims: &[ClaimsFile]) -> Vec<CommandNeed> {
    let Some(command) = input.tool_input.get("command").and_then(|c| c.as_str()) else {
        return Vec::new();
    };
    let mut needed: Vec<CommandNeed> = Vec::new();
    for file in claims {
        let mut others: Vec<&Claim> = file.claims.iter().filter(|c| c.task_id.as_ref() != Some(own)).collect();
        while let Some((rule, paths)) = evaluate_git(command, &input.cwd, &file.repo_root, &others) {
            let hit: Vec<&Claim> = others.iter().copied().filter(|c| paths.contains(&c.path)).collect();
            for c in &hit {
                if needed.iter().any(|n| n.repo == file.repo_root && n.other == c.task_id) {
                    continue;
                }
                let mut mine: Vec<String> = hit
                    .iter()
                    .filter(|o| o.task_id == c.task_id)
                    .map(|o| o.path.clone())
                    .collect();
                mine.sort();
                mine.dedup();
                needed.push(CommandNeed {
                    repo: file.repo_root.clone(),
                    other: c.task_id.clone(),
                    paths: mine,
                    kind: rule_kind(rule),
                });
            }
            let gone: Vec<Option<TaskId>> = hit.iter().map(|c| c.task_id.clone()).collect();
            others.retain(|c| !gone.contains(&c.task_id));
        }
    }
    needed
}

/// Decides one tool call of `own_task`'s session against the claims of its repos and its grants.
pub fn evaluate(
    input: &CheckInput,
    own_task: &TaskId,
    claims: &[ClaimsFile],
    grants: &GrantsFile,
    guard_git: bool,
) -> CheckDecision {
    if EDIT_TOOLS.contains(&input.tool_name.as_str()) {
        check_edit(input, own_task, claims, grants)
    } else if guard_git && input.tool_name == "Bash" {
        check_bash(input, own_task, claims, grants)
    } else {
        CheckDecision::Allow
    }
}

/// The reason given when the hook's arguments no longer parse (`run_unparsed`).
pub const STALE_HOOK_REASON: &str = "Fanout Code updated: restart this task's session to pick up the new hook.";

/// The hook of a session whose arguments do not parse (an older Fanout Code wrote its settings): it cannot tell
/// what is claimed, so it fails closed for what it guards, denying every file-tool write and every Bash command that
/// names `git` (as a word anywhere, nested shells included), and allows the rest. Always returns 0.
pub fn run_unparsed(stdin: &mut dyn Read, stdout: &mut dyn Write) -> i32 {
    let mut text = String::new();
    let input: Option<HookInput> = stdin
        .read_to_string(&mut text)
        .ok()
        .and_then(|_| serde_json::from_str(&text).ok());
    let Some(input) = input else {
        return 0;
    };
    let tool = input.tool_name.unwrap_or_default();
    let names_git = || {
        input
            .tool_input
            .as_ref()
            .and_then(|t| t.get("command"))
            .and_then(|c| c.as_str())
            .is_some_and(|c| {
                c.split(|ch: char| !(ch.is_alphanumeric() || ch == '-' || ch == '_'))
                    .any(|w| w == "git")
            })
    };
    if EDIT_TOOLS.contains(&tool.as_str()) || (tool == "Bash" && names_git()) {
        let out = serde_json::json!({"hookSpecificOutput": {
            "hookEventName": "PreToolUse",
            "permissionDecision": "deny",
            "permissionDecisionReason": STALE_HOOK_REASON,
        }});
        let _ = writeln!(stdout, "{out}");
    }
    0
}

/// What the hook command line carries: `claim-check <task-id> <grants> <notes> <log> <ask 0|1> <git 0|1> <claims…>`.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct CheckArgs {
    pub task_id: TaskId,
    pub claims_paths: Vec<PathBuf>,
    pub grants_path: PathBuf,
    pub notes_path: PathBuf,
    pub log_path: PathBuf,
    /// "Ask before editing another task's files": off, an overlapping edit is allowed and logged as `ClaimNoted`.
    pub ask_before: bool,
    pub guard_git: bool,
}

fn flag(word: &str) -> Option<bool> {
    match word {
        "1" => Some(true),
        "0" => Some(false),
        _ => None,
    }
}

impl CheckArgs {
    /// The arguments after `claim-check`; `None` when they do not parse (the caller then runs `run_unparsed`).
    pub fn parse(args: &[String]) -> Option<CheckArgs> {
        let [task, grants, notes, log, ask, guard, claims @ ..] = args else {
            return None;
        };
        Some(CheckArgs {
            task_id: TaskId::parse(task).ok()?,
            claims_paths: claims.iter().map(PathBuf::from).collect(),
            grants_path: grants.into(),
            notes_path: notes.into(),
            log_path: log.into(),
            ask_before: flag(ask)?,
            guard_git: flag(guard)?,
        })
    }
}

/// `'<exe>' claim-check '<task-id>' '<grants>' '<notes>' '<log>' <0|1> <0|1> '<claims>'…` on `PreToolUse` for the
/// file tools and Bash, five-second timeout.
pub fn check_hook_spec(exe: &Path, args: &CheckArgs) -> HookSpec {
    let q = |p: &Path| sh_single_quote(&p.display().to_string());
    let mut command = format!(
        "{} claim-check {} {} {} {} {} {}",
        q(exe),
        sh_single_quote(args.task_id.as_str()),
        q(&args.grants_path),
        q(&args.notes_path),
        q(&args.log_path),
        u8::from(args.ask_before),
        u8::from(args.guard_git),
    );
    for c in &args.claims_paths {
        command.push(' ');
        command.push_str(&q(c));
    }
    HookSpec {
        event: "PreToolUse".into(),
        matcher: Some(CHECK_MATCHER.into()),
        command,
        timeout_s: Some(5),
    }
}

#[derive(Deserialize)]
struct HookInput {
    tool_name: Option<String>,
    tool_input: Option<serde_json::Value>,
    cwd: Option<PathBuf>,
}

/// Reads one hook payload from `stdin` and answers it on `stdout`. Always returns 0: unreadable claims or grants and
/// malformed input are allowed (fail open, §5.3).
pub fn run_check(stdin: &mut dyn Read, stdout: &mut dyn Write, args: &CheckArgs) -> i32 {
    let mut text = String::new();
    let input: HookInput = match stdin
        .read_to_string(&mut text)
        .ok()
        .and_then(|_| serde_json::from_str(&text).ok())
    {
        Some(i) => i,
        None => {
            eprintln!("fanoutcode claim-check: malformed hook input; allowing");
            return 0;
        }
    };
    let input = CheckInput {
        tool_name: input.tool_name.unwrap_or_default(),
        tool_input: input.tool_input.unwrap_or(serde_json::Value::Null),
        cwd: input.cwd.unwrap_or_else(|| PathBuf::from("/")),
    };
    let claims: Vec<ClaimsFile> = args.claims_paths.iter().filter_map(|p| read_claims(p)).collect();
    let grants = read_grants(&args.grants_path);
    let mut decision = evaluate(&input, &args.task_id, &claims, &grants, args.guard_git);
    if decision == CheckDecision::Allow && args.guard_git && input.tool_name == "Bash" {
        // a command over another task's claims runs only once its single-use grants are spent on disk
        let needed = command_grants_needed(&input, &args.task_id, &claims);
        let command = input
            .tool_input
            .get("command")
            .and_then(|c| c.as_str())
            .unwrap_or_default();
        if !needed.is_empty() {
            if take_commands(&args.grants_path, command, &needed, Utc::now()) {
                log_command_ran(&args.log_path, command, &needed);
            } else {
                decision = evaluate(&input, &args.task_id, &claims, &GrantsFile::default(), true);
            }
        }
    }
    let decision = match decision {
        // "Ask before editing" off (§8): the overlapping edit is logged and allowed
        CheckDecision::Deny {
            repo,
            path: Some(path),
            other,
            ..
        } if !args.ask_before => {
            log_claim(
                &args.log_path,
                "ClaimNoted",
                &repo,
                Some(&path),
                None,
                other.as_ref(),
                &input.cwd,
            );
            CheckDecision::Allow
        }
        d => d,
    };
    let out = match decision {
        CheckDecision::Deny {
            repo,
            path,
            command,
            other,
            reason,
        } => {
            log_claim(
                &args.log_path,
                "ClaimDenied",
                &repo,
                path.as_deref(),
                command.as_deref(),
                other.as_ref(),
                &input.cwd,
            );
            Some(serde_json::json!({"hookSpecificOutput": {
                "hookEventName": "PreToolUse",
                "permissionDecision": "deny",
                "permissionDecisionReason": reason,
            }}))
        }
        CheckDecision::Allow => {
            // no `permissionDecision`: an explicit allow would skip the developer's own permission prompts
            let notes = drain_notes(&args.notes_path);
            (!notes.is_empty()).then(|| {
                serde_json::json!({"hookSpecificOutput": {
                    "hookEventName": "PreToolUse",
                    "additionalContext": notes.join("\n\n"),
                }})
            })
        }
    };
    if let Some(out) = out {
        let _ = writeln!(stdout, "{out}");
    }
    0
}

