/// Writes the TypeScript bindings to `path`.
pub fn export(path: &Path) -> Result<()> {
    let ts = Typescript::default()
        .bigint(BigIntExportBehavior::Number)
        .header(HEADER);
    builder()
        .export(ts, path)
        .map_err(|e| Error::Io(format!("Couldn't export the bindings: {e}")))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn bindings_export_every_contract_event_and_the_first_commands() {
        let dir = tempfile::tempdir().unwrap();
        let path = dir.path().join("bindings.ts");
        export(&path).unwrap();
        let ts = std::fs::read_to_string(path).unwrap();
        for name in [
            "task-changed",
            "tasks-reloaded",
            "needs-you",
            "session-exited",
            "session-attached",
            "workspace-changed",
            "views-changed",
            "cost-updated",
            "git-changes",
            "test-started",
            "test-finished",
            "team-event",
            "spec-watcher",
            "session-queue-changed",
        ] {
            assert!(ts.contains(&format!("\"{name}\"")), "{name}");
        }
        assert!(
            ts.contains("export type Task = ")
                && ts.contains("stage_entered_at: string")
                && ts.contains("state_entered_at: string")
        );
        assert!(
            ts.contains("\"NeedsYou\"") && ts.contains("reason: HandbackReason"),
            "the A1 AgentState shape reaches TypeScript"
        );
        for command in [
            "tasksAction",
            "tasksMove",
            "viewsSplit",
            "viewsSetRatio",
            "projectsOpen",
            "settingsGet",
            "settingsSet",
            "memoryRead",
            "memoryMissing",
            "gitChanges",
            "gitDiff",
            "gitIncludeOther",
            "tasksActivity",
            "hooksList",
            "hooksPlanSteps",
            "testsRun",
            "costSummary",
            "livespecAnalyze",
            "sessionsOpen",
            "sessionsTerminal",
            "sessionsAttach",
            "sessionsBring",
            "sessionsAck",
            "sessionsGet",
            "sessionsStop",
            "workspacesConvert",
            "workspacesPreviewOpen",
            "workspacesConfirmOpen",
            "contextDocsFetch",
            "jiraLink",
            "jiraCreateTask",
            "jiraStatus",
            "jiraIssue",
            "jiraComment",
        ] {
            assert!(ts.contains(&format!("async {command}(")), "{command}");
        }
        for ty in [
            "TaskPatch",
            "ActionOutcome",
            "Branch",
            "StageAction",
            "WorkspaceStatus",
            "LinkStatus",
            "ContextDoc",
            "WorkspaceImportPreview",
            "Issue",
            "JiraSite",
            "JiraLinkStatus",
            "CachedIssue",
            "Transition",
        ] {
            assert!(ts.contains(&format!("export type {ty} = ")), "{ty}");
        }
        assert!(
            ts.contains("export type ResolvedSettings = "),
            "settings_get returns the resolved settings"
        );
        assert!(ts.contains("Do not edit"));
    }
}
